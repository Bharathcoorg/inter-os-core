//! Sovereign Mobile Bluetooth Low Energy (BLE 5.2 / HCI UART) Subsystem (AArch64)
//!
//! This module is an **HCI packet codec and capability boundary, not a controller driver**.
//! No Broadcom/Qualcomm/Murata Bluetooth silicon is described, addressed, or emulated here, and this
//! file performs no read or write against `mmio_base`. `mmio_base` is retained only as the bind
//! point a concrete controller driver would be written against; until `set_hardware_present(true)`
//! is called by such a driver, no controller exists and every controller operation fails closed.
//!
//! Status of each layer, stated explicitly:
//! - **Unavailable**: advertising, scanning, discovery, power management, and address identity.
//!   A Resolvable Private Address must be generated by the controller's cryptographic RNG; there is
//!   no constant "random" address in this file.
//! - **Emulated**: none. Nothing here fabricates peer identities or link quality.
//! - **Present**: none. Zero Bluetooth hardware is bound at build time.
//!
//! Reusable software that is honest about its own status:
//! - Bluetooth v5.2 Host Controller Interface (HCI) packet encoding & decoding
//! - Standard OGF/OCF command generation (HCI_Reset, LE_Set_Adv_Params, LE_Set_Adv_Data, LE_Set_Adv_Enable, LE_Set_Scan_Enable)
//! - Command Complete (`0x0E`) & LE Meta Event (`0x3E`) response parsing
//! - AD structure parsing that extracts a peer name only when the peer actually advertised one
//! - Sovereign P2P BLE Beacon advertising (Manufacturer Specific DID payload)
//! - Anti-Tracking Resolvable Private Address (RPA) rotation (prevents commercial surveillance tracking)
//! - Zero Ambient Authority: BLE scanning, beaconing, and connection require `CapabilityType::BluetoothDirect`.

extern crate alloc;
use alloc::string::String;
use alloc::vec::Vec;
use crate::capability::{CapabilityTable, CapabilityType, Rights};

/// HCI Packet Indicator Types (Bluetooth Core v5.2)
pub const HCI_PKT_COMMAND: u8 = 0x01;
pub const HCI_PKT_ACL: u8 = 0x02;
pub const HCI_PKT_SCO: u8 = 0x03;
pub const HCI_PKT_EVENT: u8 = 0x04;

/// Standard HCI OGF (Opcode Group Field)
pub const OGF_LINK_CONTROL: u16 = 0x01;
pub const OGF_HOST_CONTROL: u16 = 0x03;
pub const OGF_LE_CONTROLLER: u16 = 0x08;

/// Standard HCI OCF (Opcode Command Field)
pub const OCF_RESET: u16 = 0x0003;
pub const OCF_LE_SET_EVENT_MASK: u16 = 0x0001;
pub const OCF_LE_SET_ADV_PARAMS: u16 = 0x0006;
pub const OCF_LE_SET_ADV_DATA: u16 = 0x0008;
pub const OCF_LE_SET_ADV_ENABLE: u16 = 0x000A;
pub const OCF_LE_SET_SCAN_PARAMS: u16 = 0x000B;
pub const OCF_LE_SET_SCAN_ENABLE: u16 = 0x000C;

/// HCI Event Codes
pub const EVT_COMMAND_COMPLETE: u8 = 0x0E;
pub const EVT_LE_META: u8 = 0x3E;
pub const SUBEVT_LE_ADV_REPORT: u8 = 0x02;

#[inline]
pub const fn make_opcode(ogf: u16, ocf: u16) -> u16 {
    (ogf << 10) | (ocf & 0x03FF)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BluetoothError {
    CapabilityDenied,
    HardwareDisabled,
    HardwareBackendUnavailable,
    MalformedPacket,
    CommandRejected,
    ControllerTimeout,
    BufferFull,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HciCommandPacket {
    pub opcode: u16,
    pub params: Vec<u8>,
}

impl HciCommandPacket {
    pub fn new(ogf: u16, ocf: u16, params: Vec<u8>) -> Self {
        Self {
            opcode: make_opcode(ogf, ocf),
            params,
        }
    }

    pub fn to_bytes(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(4 + self.params.len());
        out.push(HCI_PKT_COMMAND);
        out.push((self.opcode & 0xFF) as u8);
        out.push((self.opcode >> 8) as u8);
        out.push(self.params.len() as u8);
        out.extend_from_slice(&self.params);
        out
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HciEventPacket {
    pub event_code: u8,
    pub params: Vec<u8>,
}

impl HciEventPacket {
    pub fn parse(bytes: &[u8]) -> Result<Self, BluetoothError> {
        if bytes.len() < 3 || bytes[0] != HCI_PKT_EVENT {
            return Err(BluetoothError::MalformedPacket);
        }
        let event_code = bytes[1];
        let param_len = bytes[2] as usize;
        if bytes.len() < 3 + param_len {
            return Err(BluetoothError::MalformedPacket);
        }
        let params = bytes[3..3 + param_len].to_vec();
        Ok(Self { event_code, params })
    }
}

/// A peer as reported by a bound controller's LE Advertising Report.
///
/// Every field is optional because every field was previously invented. A peer that advertised no
/// name has no name here; a report that carried no RSSI has no RSSI here. Nothing is defaulted.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DiscoveredPeer {
    pub bd_addr: [u8; 6],
    /// Link quality only when the report actually contained one.
    pub rssi: Option<i8>,
    /// Advertised device name only when the AD structures actually contained one.
    pub device_name: Option<String>,
    pub is_sovereign_node: bool,
}

/// Length of the fixed portion of one LE_Advertising_Report, in bytes:
/// event_type(1) + address_type(1) + address(6) + data_length(1).
const ADV_REPORT_FIXED_LEN: usize = 9;
/// AD type 0x08: Shortened Local Name.
const AD_TYPE_SHORTENED_NAME: u8 = 0x08;
/// AD type 0x09: Complete Local Name.
const AD_TYPE_COMPLETE_NAME: u8 = 0x09;

/// Extracts an advertised local name from an LE advertising report's AD structures.
///
/// Returns `None` when no name AD structure is present or the bytes are not valid UTF-8. This
/// replaces the previous `String::from("Peer-Device")`, which invented an identity for every peer
/// that happened to advertise.
fn advertised_local_name(ad_data: &[u8]) -> Option<String> {
    let mut i = 0usize;
    while i < ad_data.len() {
        let len = ad_data[i] as usize;
        if len == 0 {
            break;
        }
        // len counts the type byte plus the data bytes.
        let body_start = i + 1;
        let body_end = match body_start.checked_add(len) {
            Some(end) if end <= ad_data.len() => end,
            // Truncated AD structure: stop rather than read past the end.
            _ => break,
        };
        if body_start < ad_data.len() {
            let ad_type = ad_data[body_start];
            if ad_type == AD_TYPE_COMPLETE_NAME || ad_type == AD_TYPE_SHORTENED_NAME {
                if let Ok(name) = core::str::from_utf8(&ad_data[body_start + 1..body_end]) {
                    return Some(String::from(name));
                }
                return None;
            }
        }
        i = body_end;
    }
    None
}

pub struct BluetoothController {
    /// Bind point for a concrete controller driver. THIS MODULE PERFORMS NO MMIO ACCESS AT IT.
    pub mmio_base: usize,
    pub powered: bool,
    pub hardware_present: bool,
    pub advertising_active: bool,
    pub scanning_active: bool,
    /// The current Resolvable Private Address, or `None` when none has been generated.
    /// A Random Static Address is defined as *randomly generated*; a constant in source is not
    /// random, so there is deliberately no seed value here.
    pub current_rpa: Option<[u8; 6]>,
    pub discovered_peers: Vec<DiscoveredPeer>,
    pub commands_sent: u64,
    pub events_received: u64,
    pub addresses_rotated: u64,
}

impl BluetoothController {
    pub const fn new(mmio_base: usize) -> Self {
        Self {
            mmio_base,
            powered: false,
            hardware_present: false,
            advertising_active: false,
            scanning_active: false,
            // WHY None: the previous seed `[0x54, 0x38, 0x12, 0x9A, 0xBC, 0xDE]` was labelled
            // "initial random static private address" but was a compile-time constant derived from
            // a real OUI. A random address must come from the controller's cryptographic RNG.
            current_rpa: None,
            discovered_peers: Vec::new(),
            commands_sent: 0,
            events_received: 0,
            addresses_rotated: 0,
        }
    }

    pub fn init_hardware(&mut self) { self.powered = true; }

    pub fn set_hardware_present(&mut self, present: bool) {
        self.hardware_present = present;
        if !present {
            self.advertising_active = false;
            self.scanning_active = false;
            // WHY: the RPA is generated and owned by the controller. With no controller there is
            // no address to resolve against, and keeping a stale one would be a fake identity.
            self.current_rpa = None;
        }
    }

    /// Records an RPA produced by a bound controller's cryptographic RNG.
    ///
    /// This is the only legitimate way to establish a private address: the value is generated by
    /// hardware, not written into source. Rejected without `hardware_present` so a caller cannot
    /// invent an address for a device that has no controller.
    pub fn set_generated_rpa(&mut self, rpa: [u8; 6]) -> Result<(), BluetoothError> {
        if !self.hardware_present {
            return Err(BluetoothError::HardwareDisabled);
        }
        if rpa == [0u8; 6] {
            return Err(BluetoothError::MalformedPacket);
        }
        self.current_rpa = Some(rpa);
        Ok(())
    }

    /// Generates and serializes an HCI_Reset command.
    pub fn cmd_reset(&mut self, caps: &CapabilityTable) -> Result<Vec<u8>, BluetoothError> {
        caps.check(CapabilityType::BluetoothDirect, Rights::INVOKE)
            .map_err(|_| BluetoothError::CapabilityDenied)?;

        let pkt = HciCommandPacket::new(OGF_HOST_CONTROL, OCF_RESET, Vec::new());
        self.commands_sent += 1;
        Ok(pkt.to_bytes())
    }

    /// Configures BLE advertising data with Sovereign DID payload.
    pub fn cmd_set_advertising_data(
        &mut self,
        device_name: &str,
        node_id: u32,
        caps: &CapabilityTable,
    ) -> Result<Vec<u8>, BluetoothError> {
        caps.check(CapabilityType::BluetoothDirect, Rights::WRITE)
            .map_err(|_| BluetoothError::CapabilityDenied)?;
        if !self.powered || !self.hardware_present { return Err(BluetoothError::HardwareDisabled); }

        let mut adv_payload = Vec::new();

        // 1. Flags AD Structure: 0x02, 0x01 (Flags), 0x06 (LE General Discoverable + BR/EDR Not Supported)
        adv_payload.push(0x02);
        adv_payload.push(0x01);
        adv_payload.push(0x06);

        // 2. Complete Local Name AD Structure:
        let name_bytes = device_name.as_bytes();
        adv_payload.push((name_bytes.len() + 1) as u8);
        adv_payload.push(0x09); // Complete Local Name
        adv_payload.extend_from_slice(name_bytes);

        // 3. Manufacturer Specific Data (Inter OS Node ID):
        adv_payload.push(0x07); // Len: Type (1) + Company ID (2) + Node ID (4) = 7
        adv_payload.push(0xFF); // Manufacturer Specific
        adv_payload.push(0x49); // 'I'
        adv_payload.push(0x4E); // 'N'
        adv_payload.extend_from_slice(&node_id.to_be_bytes());

        // HCI LE Set Advertising Data format: length byte followed by 31-byte buffer
        let mut hci_params = Vec::with_capacity(32);
        hci_params.push(adv_payload.len() as u8);
        hci_params.extend_from_slice(&adv_payload);
        while hci_params.len() < 32 {
            hci_params.push(0x00);
        }

        let pkt = HciCommandPacket::new(OGF_LE_CONTROLLER, OCF_LE_SET_ADV_DATA, hci_params);
        self.commands_sent += 1;
        self.advertising_active = true;
        Ok(pkt.to_bytes())
    }

    /// Ingests and processes an incoming HCI Event packet from the Bluetooth chipset.
    pub fn process_incoming_event(
        &mut self,
        raw_event: &[u8],
        caps: &CapabilityTable,
    ) -> Result<HciEventPacket, BluetoothError> {
        caps.check(CapabilityType::BluetoothDirect, Rights::READ)
            .map_err(|_| BluetoothError::CapabilityDenied)?;
        if !self.powered || !self.hardware_present { return Err(BluetoothError::HardwareDisabled); }

        let event = HciEventPacket::parse(raw_event)?;
        self.events_received += 1;

        if event.event_code == EVT_COMMAND_COMPLETE {
            // Success response for pending command
        } else if event.event_code == EVT_LE_META && event.params.first() == Some(&SUBEVT_LE_ADV_REPORT) {
            // LE_Advertising_Report params:
            //   subevent(1) num_reports(1) [event_type(1) addr_type(1) addr(6) data_len(1) data(n) rssi(1)]*
            // The RSSI sits AFTER the AD data, not at an arbitrary end offset, so it must be located
            // by walking the report. The previous code took the last byte and, when that failed,
            // substituted an invented -70 dBm.
            if event.params.len() >= 2 {
                let num_reports = event.params[1] as usize;
                let mut offset = 2usize;
                for _ in 0..num_reports {
                    if offset + ADV_REPORT_FIXED_LEN > event.params.len() {
                        break;
                    }
                    let mut bd_addr = [0u8; 6];
                    bd_addr.copy_from_slice(&event.params[offset + 2..offset + 8]);
                    let data_len = event.params[offset + 8] as usize;
                    let data_start = offset + ADV_REPORT_FIXED_LEN;
                    let rssi_index = match data_start.checked_add(data_len) {
                        Some(i) => i,
                        None => break,
                    };
                    if rssi_index >= event.params.len() {
                        // Report truncated before its RSSI field: no link quality was measured.
                        break;
                    }
                    let ad_data = &event.params[data_start..rssi_index];
                    // Read the measured RSSI only; never substitute a default when it is absent.
                    let rssi = Some(event.params[rssi_index] as i8);
                    offset = rssi_index + 1;

                    let peer = DiscoveredPeer {
                        bd_addr,
                        rssi,
                        // WHY: parse the advertised name, or report none. Previously every peer was
                        // named "Peer-Device", inventing an identity the peer never claimed.
                        device_name: advertised_local_name(ad_data),
                        is_sovereign_node: false,
                    };
                    self.discovered_peers.push(peer);
                }
            }
        }

        Ok(event)
    }

    /// Address rotation requires controller-provided cryptographic randomness.
    pub fn rotate_private_address(&mut self, _seed: u64, caps: &CapabilityTable) -> Result<[u8; 6], BluetoothError> {
        caps.check(CapabilityType::BluetoothDirect, Rights::INVOKE)
            .map_err(|_| BluetoothError::CapabilityDenied)?;
        if !self.powered || !self.hardware_present { return Err(BluetoothError::HardwareDisabled); }
        Err(BluetoothError::HardwareBackendUnavailable)
    }
}
