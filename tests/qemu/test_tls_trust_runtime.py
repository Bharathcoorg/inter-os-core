class Guest:
    """One private QEMU phone: its own disks, its own serial and monitor sockets."""

    def __init__(self):
        self.proc = None
        self.ser = None
        self.mon = None
        self.reader = None
        self._stop = threading.Event()

    def start(self):
        qemu = find_qemu("qemu-system-x86_64.exe")
        args = [
            qemu,
            "-machine", "q35",
            "-cpu", "qemu64",
            "-device", "piix3-ide,id=ide",
            # WHY snapshot=on on both drives: this suite must not move the boot
            # image another agent is relying on, and must not leave marks on the
            # throwaway disk either. The overlay keeps the run hermetic.
            "-drive", f"file={BOOT_IMAGE},format=raw,if=none,id=bootd,snapshot=on",
            "-device", "ide-hd,bus=ide.0,unit=0,drive=bootd,bootindex=1",
            "-drive", f"file={DATA_DISK},format=raw,if=none,id=datad,snapshot=on",
            "-device", "ide-hd,bus=ide.0,unit=1,drive=datad",
            # User-mode networking: the guest reaches this host's loopback as
            # 10.0.2.2, which is where the local peer is listening.
            "-netdev", "user,id=net0",
            "-device", "e1000,netdev=net0,mac=52:54:00:12:34:56",
            "-m", "1024M",
            "-display", "none",
            "-chardev", f"socket,id=ser0,host=127.0.0.1,port={SERIAL_PORT},"
                        f"server=on,wait=off",
            "-serial", "chardev:ser0",
            "-chardev", f"socket,id=mon0,host=127.0.0.1,port={MONITOR_PORT},"
                        f"server=on,wait=off",
            "-mon", f"chardev=mon0,mode=readline",
            "-no-reboot",
        ]
        args.extend(qemu_x86_audio_args(qemu))
        self.proc = subprocess.Popen(args, cwd=ROOT)

        for _ in range(120):
            try:
                self.ser = socket.create_connection(("127.0.0.1", SERIAL_PORT), timeout=1)
                break
            except OSError:
                if self.proc.poll() is not None:
                    raise RuntimeError("QEMU exited before its serial socket answered")
                time.sleep(0.25)
        if self.ser is None:
            raise RuntimeError("guest serial never answered")
        self.ser.settimeout(0.5)
        self.reader = SerialReader(self.ser)
        self.reader.captured_logs = logs

        def pump():
            buf = b""
            while not self._stop.is_set():
                try:
                    data = self.ser.recv(8192)
                    if not data:
                        time.sleep(0.1)
                        continue
                    buf += data
                    while b"\n" in buf:
                        line, buf = buf.split(b"\n", 1)
                        text = line.decode("utf-8", errors="replace").strip()
                        if text:
                            logs.append(text)
                except socket.timeout:
                    continue
                except OSError:
                    return

        threading.Thread(target=pump, daemon=True).start()

        try:
            self.mon = socket.create_connection(("127.0.0.1", MONITOR_PORT), timeout=10)
            self.mon.settimeout(3.0)
        except OSError:
            self.mon = None

    def send(self, line):
        self.reader.send(line if line.endswith("\n") else line + "\n")

    def console(self, line, expect, budget=ANCHOR_TIMEOUT):
        """One console verb, and the acknowledgement line it produced."""
        since = len(logs)
        self.send(line)
        hit, text = wait_for(expect, budget, since)
        return text or "(no %r within %.0fs)" % (expect, budget)

    def boot_to_home(self, budget=300.0):
        since = len(logs)
        hit, _ = wait_for(["Step 5: Initial presentation complete",
                           "home screen canvas initialized"], budget, since)
        if not hit:
            raise RuntimeError("the guest never finished its first presentation")
        time.sleep(3.0)

    def launch_browser(self, budget=180.0):
        since = len(logs)
        self.send("APP_LAUNCH browser")
        hit, _ = wait_for(["Browser canvas presented to scanout buffer.",
                           "[BROWSER APP]"], budget, since)
        if not hit:
            raise RuntimeError("the browser never came up")
        time.sleep(2.0)

    def shutdown(self):
        """Power the guest off and make sure the process is really gone."""
        try:
            self.send("POWEROFF")
        except OSError:
            pass
        deadline = time.time() + 15
        while time.time() < deadline and self.proc.poll() is None:
            try:
                send_monitor_cmd(self.mon, "system_poweroff")
            except Exception:
                pass
            time.sleep(1.0)
        if self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                self.proc.kill()
                self.proc.wait(timeout=10)
        self._stop.set()
        for sock in (self.ser, self.mon):
            try:
                if sock:
                    sock.close()
            except OSError:
                pass
        return self.proc.poll()


# ------------------------------------------------------------- the dials --------

def type_url(guest, url, pause=0.05):
    guest.send("TAP %d %d" % PILL)
    time.sleep(1.2)
    guest.send("TAP %d %d" % CLEAR_CHIP)
    time.sleep(1.2)
    for char in url:
        guest.send("INPUT_KEY %d" % ord(char))
        time.sleep(pause)
    guest.send("INPUT_KEYCODE ENTER")
    time.sleep(1.0)


def parse_window(window):
    """Everything measurable in one dial's slice of the console."""
    row = {"echoed_url": None, "verdict": None, "verdict_line": None,
           "bytes": None, "trunc": None, "err": None, "doc_len": None,
           "lines": [log_line(l) for l in window], "crash": []}
    for index, line in enumerate(window):
        if "Navigation target URL:" in line and index + 1 < len(window):
            row["echoed_url"] = log_line(window[index + 1])[:128]
    for line in window:
        if REFUSED in line:
            row["verdict"], row["verdict_line"] = "refused", line
        match = re.search(r"fetch_over_tcp bytes=(\d+) trunc=(\d) err=(-?\d+)", line)
        if match:
            row["bytes"] = int(match.group(1))
            row["trunc"] = match.group(2) == "1"
            row["err"] = int(match.group(3))
            row["verdict"] = "carried"
            row["verdict_line"] = line
        match = re.search(r"decode: doc_len=(\d+)", line)
        if match:
            row["doc_len"] = int(match.group(1))
        for needle in OTHER_VERDICTS:
            if needle in line and row["verdict"] not in ("carried",):
                row["verdict"], row["verdict_line"] = needle, line
        if any(mark in line for mark in CRASH_MARKS) and "REJECT" not in line:
            row["crash"].append(line)
    return row


def dial(guest, peer, url, budget=150.0):
    """One navigation, and what both the guest and the peer said about it."""
    since = len(logs)
    before = len(peer.records)
    type_url(guest, url)

    # Wait for the browser's own verdict and, when it is a fetch, for the decode
    # line that follows it -- `bytes=` alone does not say the document was handed on.
    deadline = time.time() + budget
    row = None
    while time.time() < deadline:
        window = logs[since:]
        row = parse_window(window)
        if row["verdict"] == "refused":
            break
        if row["bytes"] is not None and row["doc_len"] is not None:
            break
        if row["verdict"] in OTHER_VERDICTS:
            break
        time.sleep(0.4)

    row = row or parse_window(logs[since:])
    row["url"] = url
    record = peer.wait_for_record(before, 30.0)
    row["peer"] = record
    if record and "GET" in (record.get("request") or ""):
        match = re.search(r"GET (\S+)", record["request"])
        row["peer_path"] = match.group(1) if match else None
    else:
        row["peer_path"] = None
    row["peer_handshake"] = record["handshake"] if record else "no connection reached the listener"
    return row


def peer_saw_no_handshake(row):
    """True only when the listener really took the connection and no keys changed.

    WHY a function and not the `or row["peer_path"] is None` it replaces: a dial that
    never opened a socket -- guest wedged, address bar not focused, nothing on the wire
    -- leaves `peer_path` None as well, so written that way the check passed on the
    absence of the very witness it claims to assert on, and dial 1 would have gone
    green without the peer ever being involved. The client runs the verifier inside the
    handshake and only emits Client Finished once it rejected nothing
    (`perform_tls_handshake` in apps/browser/src/http.rs), so a refusal at the trust
    store must arrive here as a connection whose TLS attempt never completed. Both
    shapes of that count: an alert that made `wrap_socket` raise, and a reset that lands
    before the server-side handshake resolves.
    """
    record = row.get("peer")
    if not record:
        return False
    handshake = record.get("handshake") or ""
    return ((handshake.startswith("refused") or handshake.startswith("reset before keys"))
            and row.get("peer_path") is None)


def install_anchor(guest, der_path, label):
    """Send a root DER over the console the way an operator would: in chunks."""
    with open(der_path, "rb") as handle:
        der = handle.read()
    hex_all = der.hex()
    transcript = [guest.console("TLS_TRUST_BEGIN %d" % len(der), "[TLS_TRUST] READY")]
    for offset in range(0, len(der), ANCHOR_CHUNK_BYTES):
        part = hex_all[offset * 2:(offset + ANCHOR_CHUNK_BYTES) * 2]
        line = "TLS_TRUST_CHUNK %d %s" % (offset, part)
        assert len(line) <= MAX_CONSOLE_LINE, "chunk line would be dropped by the console"
        # WHY the offset is part of the needle: acks lag one round trip behind when
        # the guest is busy, and a bare "CHUNK" match lets one chunk's ack answer
        # for the next and hides a chunk the guest never received.
        transcript.append(guest.console(line, "[TLS_TRUST] CHUNK offset=%d " % offset))
    transcript.append(guest.console("TLS_TRUST_COMMIT %s" % label, "[TLS_TRUST] ANCHOR"))
    return len(der), transcript


def revoke_anchor(guest, position=0):
    return guest.console("TLS_TRUST_REVOKE %d" % position, "[TLS_TRUST] REVOKED")


def list_anchors(guest):
    """`TLS_TRUST_LIST` and every ``[TLS_TRUST]`` line the reply produced.

    WHY the whole block and not the first line: the kernel prints the count on one
    line (`anchors=N`) and the labels on the lines after it (`0 bytes=399
    label=suite-ca`), so a check that only ever saw the count line could never see
    the label it claims to be asserting on.
    """
    since = len(logs)
    guest.send("TLS_TRUST_LIST")
    hit, _ = wait_for("[TLS_TRUST] anchors=", ANCHOR_TIMEOUT, since)
    if hit is None:
        return "(TLS_TRUST_LIST never answered within %.0fs)" % ANCHOR_TIMEOUT
    time.sleep(0.6)  # let the per-anchor lines land before collecting the window
    return " | ".join(log_line(l) for l in logs[since:] if "[TLS_TRUST]" in l)


# ------------------------------------------------------------- reporting --------

class Ledger:
    def __init__(self):
        self.rows = []

    def check(self, name, ok, detail):
        self.rows.append((name, bool(ok), detail))
        print("  [%s] %s\n         %s" % ("PASS" if ok else "FAIL", name, detail))
        return bool(ok)

    @property
    def failed(self):
        return [name for name, ok, _ in self.rows if not ok]


def describe(row):
    lines = ["    url    %s" % row.get("url"),
             "    verdict %s  %s" % (row.get("verdict"), (row.get("verdict_line") or "")[:170]),
             "    echoed  %r" % row.get("echoed_url"),
             "    payload bytes=%s trunc=%s err=%s doc_len=%s"
             % (row.get("bytes"), row.get("trunc"), row.get("err"), row.get("doc_len")),
             "    peer    %s  request=%r" % (row.get("peer_handshake"), row.get("peer_path"))]
    return "\n".join(lines)


class NoPeer:
    """Stand-in so the public dial reuses `dial()` with no listener to consult.

    The public site is the peer, so there is no host-side record of it: the only
    honest witness for that phase is what the guest itself printed.
    """

    records = []

    def wait_for_record(self, before, budget=0.0):
        return None


def write_artifacts(peer, rows):
    """Save the raw serial stream and this peer's per-connection records.

    WHY on disk and not only on stdout: every claim the report makes is a slice of one
    of these two, and the printed form truncates each line to 170 characters -- enough
    to read a verdict, not nearly enough to re-check one. Both go under the work
    directory, which is inside the gitignored `target/verify/` tree.
    """
    serial_path = os.path.join(WORK_DIR, "guest-serial.log")
    try:
        with open(serial_path, "w", encoding="utf-8", errors="replace") as handle:
            handle.write("\n".join(logs) + "\n")
        print("[tls-suite] teardown: wrote %s (%d lines)" % (serial_path, len(logs)))
    except OSError as exc:
        print("[tls-suite] teardown: serial log could not be written: %r" % exc)
    records_path = os.path.join(WORK_DIR, "peer-records.json")
    try:
        with open(records_path, "w", encoding="utf-8") as handle:
            json.dump({"dials": [{"url": r.get("url"), "verdict": r.get("verdict"),
                                  "bytes": r.get("bytes"), "trunc": r.get("trunc"),
                                  "err": r.get("err"), "doc_len": r.get("doc_len"),
                                  "echoed_url": r.get("echoed_url"),
                                  "peer": r.get("peer")} for _, r in rows],
                       "connections": peer.records if peer else []},
                      handle, indent=2, default=str)
        print("[tls-suite] teardown: wrote %s (%d connections observed)"
              % (records_path, len(peer.records) if peer else 0))
    except (OSError, TypeError, ValueError) as exc:
        print("[tls-suite] teardown: peer records could not be written: %r" % exc)


def main():
    break_which = os.environ.get("TLS_SUITE_BREAK", "")
    want_public = os.environ.get("TLS_SUITE_PUBLIC", "1") != "0"

    print("[tls-suite] device TLS runtime suite")
    print("[tls-suite] peer: LOCAL test CA on %s:%d (the guest dials %s)"
          % (PEER_HOST, PEER_PORT, DIAL_HOST))
    print("[tls-suite] ports: serial %d, monitor %d, peer %d -- no Studio, no QMP"
          % (SERIAL_PORT, MONITOR_PORT, PEER_PORT))
    if break_which == "skip-install":
        print("[tls-suite] SELF-TEST: the install dial is suppressed, so this run MUST fail")

    if not os.path.exists(BOOT_IMAGE):
        print("SKIP: boot image missing: %s" % BOOT_IMAGE)
        return 0
    if not have_qemu():
        print("SKIP: qemu-system-x86_64 is not available on this machine")
        return 0
    try:
        import cryptography  # noqa: F401
    except ImportError:
        print("SKIP: the local test CA needs the `cryptography` module, absent here")
        return 0

    if DATA_DISK == MASTER_DISK:
        print("FAIL: DATA_DISK_PATH points at the 6 GiB master image, which this "
              "suite must never attach, copy or hash: %s" % MASTER_DISK)
        return 1

    # WHAT THIS IMAGE IS. Weighed before anything is created, because the suite builds
    # nothing: a run on an image older than the sources its dials exercise would report
    # yesterday's bytes as the current platform, and the sha256 printed below cannot
    # tell the two apart -- it only proves this suite did not move the image.
    source_stamp, source_path = newest_source()
    stale = source_stamp > os.path.getmtime(BOOT_IMAGE)
    allow_stale = os.environ.get("TLS_SUITE_ALLOW_STALE_IMAGE") == "1"
    currency = "%s (%d bytes) built %s | newest source %s at %s" % (
        os.path.basename(BOOT_IMAGE), os.path.getsize(BOOT_IMAGE),
        when(os.path.getmtime(BOOT_IMAGE)),
        os.path.relpath(source_path, ROOT).replace("\\", "/") if source_path else "(none)",
        when(source_stamp))
    print("[tls-suite] image under test: %s" % currency)
    if stale and not allow_stale:
        print("FAIL: the image predates the sources these dials exercise, so a green run "
              "here would certify the wrong bytes. Rebuild it with "
              "`python tools/interos.py build demo`, or set TLS_SUITE_ALLOW_STALE_IMAGE=1 "
              "to run anyway and label the result as the image's, not the tree's.")
        return 1

    os.makedirs(WORK_DIR, exist_ok=True)
    created_disk = not os.path.exists(DATA_DISK)
    if created_disk:
        with open(DATA_DISK, "wb") as handle:
            handle.truncate(DISK_BYTES)
    print("[tls-suite] data disk: %s (%d MiB, throwaway%s)"
          % (DATA_DISK, os.path.getsize(DATA_DISK) // (1024 * 1024),
             ", created this run" if created_disk else ", reused"))
    image_before = sha256_of(BOOT_IMAGE)
    print("[tls-suite] boot image sha256 before: %s" % image_before)

    for port in (SERIAL_PORT, MONITOR_PORT, PEER_PORT):
        kill_proc_on_port(port)
    time.sleep(0.5)

    ledger = Ledger()
    peer = None
    guest = None
    document = make_document()
    answer, head_len = make_answer(document)
    expected_bytes = len(answer)
    rows = []
    notes = {}
    exit_code = 1

    # Recorded so a report of the four dials always says which image judged them, even
    # when the operator overrode the staleness gate above.
    notes["image"] = currency + ("  <-- OLDER than its sources, run by override"
                                 if stale else "")
    ledger.check(
        "the boot image under test is at least as new as the sources these dials exercise",
        (not stale) or allow_stale, currency)

    try:
        peer = LocalPeer().start()
        peer.set_answer(answer)
        print("[tls-suite] peer presenting a chain under %s (%d bytes)"
              % (os.path.basename(peer.root_der_path), os.path.getsize(peer.root_der_path)))
        print("[tls-suite] document is %d bytes; the peer's whole answer is %d bytes"
              % (len(document), expected_bytes))

        guest = Guest()
        guest.start()
        guest.boot_to_home()
        # The browser is the only userspace program that reaches syscalls 162/163, so
        # there is no dial until it is on screen and its address bar has focus.
        guest.launch_browser()

        # -- dial 1: a fresh device trusts nobody -------------------------------
        boot_lines = [log_line(l) for l in logs if "[TLS_TRUST]" in l]
        notes["boot"] = boot_lines[0] if boot_lines else "(none)"
        before_list = list_anchors(guest)
        rows.append(("refused with no anchor", dial(guest, peer, LOCAL_URL_BASE + "dial-1",
                                                    budget=150.0)))
        row = rows[-1][1]
        ledger.check(
            "dial 1: the guest refused a chain with no anchor installed",
            row["verdict"] == "refused",
            "guest said: %s" % (row["verdict_line"] or "no verdict within the window"))
        ledger.check(
            "dial 1: the peer was reached and completed no handshake for it",
            peer_saw_no_handshake(row),
            "peer said: %s, request path=%r" % (row["peer_handshake"], row["peer_path"]))
        ledger.check(
            "dial 1: the store reports itself empty before anything was installed",
            "anchors=0" in before_list,
            "TLS_TRUST_LIST said: %s" % before_list[:160])
        if row["verdict"] == DNS_UNRESOLVED:
            # The name got no DNS answer and the guest would not invent an address --
            # which is the platform behaving correctly and this suite dialling the
            # wrong thing. Say that in the guest's own words and name the knob, rather
            # than leaving a window with no verdict as the only evidence.
            notes["dial path"] = (
                "BLOCKED before TLS: %s Retry with the literal address: "
                "TLS_SUITE_HOST=%s python tests/qemu/test_tls_trust_runtime.py"
                % ((row["verdict_line"] or "")[:180], GATEWAY_ADDRESS))
            print("[tls-suite] dial path: %s" % notes["dial path"])

        # -- dial 2: the operator installs the public root ----------------------
        if break_which == "skip-install":
            notes["install"] = "(suppressed by TLS_SUITE_BREAK=skip-install)"
            ledger.check("dial 2: the anchor was installed", False,
                         "deliberately suppressed by the self-test knob")
        else:
            anchor_bytes, install_lines = install_anchor(guest, peer.root_der_path, LABEL)
            notes["install"] = install_lines
            after_list = list_anchors(guest)
            committed = [l for l in install_lines if "[TLS_TRUST] ANCHOR" in l]
            ledger.check(
                "dial 2: the root DER committed as an anchor in the store",
                bool(committed) and LABEL in after_list,
                "%s | TLS_TRUST_LIST: %s" % (committed[-1][:160] if committed else
                                             "(no ANCHOR ack)", after_list[:160]))
            notes["anchor_bytes"] = anchor_bytes

        # -- dial 3: real bytes over the verified channel -----------------------
        rows.append(("carried bytes after install",
                     dial(guest, peer, LOCAL_URL_BASE + "dial-2", budget=180.0)))
        row = rows[-1][1]
        carried = (row["bytes"] == expected_bytes and row["trunc"] is False
                   and row["err"] == 0)
        ledger.check(
            "dial 3: the same fetch now succeeds, and the payload is the one this "
            "suite chose (%d bytes, trunc=0, err=0)" % expected_bytes,
            carried,
            "guest said: %s" % (row["verdict_line"] or "no fetch line within the window"))
        ledger.check(
            "dial 3: the document reached the parser at exactly the length written "
            "(decode: doc_len=%d)" % len(document),
            row["doc_len"] == len(document),
            "decode: doc_len=%s, answer was %d header + %d document bytes"
            % (row["doc_len"], head_len, len(document)))
        ledger.check(
            "dial 3: the peer completed the handshake and read the plaintext GET for "
            "this dial",
            row["peer_handshake"] == "completed" and row["peer_path"] == "/dial-2",
            "peer said: %s, request path=%r" % (row["peer_handshake"], row["peer_path"]))
        ledger.check(
            "dial 3: the address the guest navigated to is the one this suite typed",
            row["echoed_url"] == LOCAL_URL_BASE + "dial-2",
            "echoed address: %r" % row["echoed_url"])
        if (row["verdict"] == "refused" and break_which != "skip-install"
                and row["peer_handshake"] != "no connection reached the listener"):
            # The anchor went in and the peer was reached, so an empty store is not
            # what made this dial fail. The guest prints one sentence for every
            # verifier rejection, so name what is left to look at -- the reference
            # identity this run dialled, and where the chain it was judged against is.
            notes["dial path"] = (
                "the anchor was installed and the peer was reached, yet the client "
                "still refused %r (%s). The chain it was judged against is at %s"
                % (DIAL_HOST,
                   "an address identity, matched against iPAddress entries only"
                   if DIAL_HOST == GATEWAY_ADDRESS else "a DNS name identity",
                   os.path.join(WORK_DIR, "suite-leaf-chain.pem")))
            print("[tls-suite] dial path: %s" % notes["dial path"])

        # -- dial 4: withdraw the anchor and the same dial refuses again --------
        revoke_line = ("" if break_which == "skip-install" else revoke_anchor(guest))
        notes["revoke"] = revoke_line
        after_revoke = list_anchors(guest)
        rows.append(("refused again after revoke",
                     dial(guest, peer, LOCAL_URL_BASE + "dial-3", budget=150.0)))
        row = rows[-1][1]
        ledger.check(
            "dial 4: the revoked store is empty",
            "anchors=0" in after_revoke and "REVOKED" in revoke_line,
            "%s | TLS_TRUST_LIST: %s" % (revoke_line[:120] or "(no revoke sent)",
                                          after_revoke[:160]))
        ledger.check(
            "dial 4: the same chain the store just accepted is refused again",
            row["verdict"] == "refused",
            "guest said: %s" % (row["verdict_line"] or "no verdict within the window"))
        ledger.check(
            "dial 4: and the peer again completed no handshake",
            peer_saw_no_handshake(row),
            "peer said: %s, request path=%r" % (row["peer_handshake"], row["peer_path"]))

        # Every local dial typed a different path, so an address bar that kept the
        # previous navigation would show up here as an echo this suite did not write
        # -- and a stale bar is exactly the kind of thing that makes a "refused"
        # verdict belong to a dial that never happened.
        mistyped = [(t, r.get("echoed_url")) for t, r in rows
                    if r.get("echoed_url") != r.get("url")]
        ledger.check(
            "every dial navigated to exactly the address this suite typed",
            not mistyped,
            "all three echoes matched" if not mistyped
            else "dial %r echoed %r" % (mistyped[0][0], mistyped[0][1]))

        # -- public-chain phase: reported, never assumed ------------------------
        if want_public:
            print("\n[tls-suite] public-chain phase (reported, not gated): installing "
                  "the committed ISRG Root X1 fixture and dialing a real site")
            if not os.path.exists(PUBLIC_ANCHOR):
                notes["public"] = ("NOT VERIFIED: the public anchor fixture is not at "
                                   "%s" % PUBLIC_ANCHOR)
            else:
                size, lines = install_anchor(guest, PUBLIC_ANCHOR, PUBLIC_LABEL)
                public_row = dial(guest, NoPeer(), PUBLIC_URL, budget=240.0)
                if public_row["bytes"] and public_row["err"] == 0:
                    notes["public"] = (
                        "PUBLIC CHAIN VERIFIED IN THIS RUN: %d bytes carried over TLS "
                        "under ISRG Root X1 (%d-byte anchor, %d chunks)"
                        % (public_row["bytes"], size,
                           len([l for l in lines if "CHUNK" in l])))
                else:
                    notes["public"] = (
                        "NOT VERIFIED against a public chain: %s (verdict %s; %s)"
                        % (PUBLIC_URL, public_row["verdict"],
                           (public_row["verdict_line"] or "no verdict line")[:120]))
                revoke_anchor(guest)
            print("[tls-suite] public-chain result: %s" % notes["public"])

        crash = [line for _, r in rows for line in r["crash"]]
        ledger.check("the guest recorded no kernel crash across the four dials",
                     not crash, crash[0][:160] if crash else "no crash marks in the window")

    except BaseException:
        import traceback
        trace = traceback.format_exc()
        print(trace, flush=True)
        ledger.check("the suite itself ran to completion", False, trace[-400:])
    finally:
        # Teardown happens before the verdict is printed, because the verdict has to
        # be able to say that the boot image moved or that a port is still live.
        if guest is not None:
            guest.shutdown()
        if peer is not None:
            peer.stop()

        print("\n[tls-suite] what each local dial produced, in order\n")
        for tag, row in rows:
            print("  [%s]" % tag)
            print(describe(row))
        print("\n[tls-suite] console transcript")
        for key, value in notes.items():
            if isinstance(value, list):
                print("  %s:" % key)
                for line in value:
                    print("     %s" % (line or "")[:170])
            else:
                print("  %s: %s" % (key, value))

        leftover = []
        for port in (SERIAL_PORT, MONITOR_PORT, PEER_PORT):
            try:
                probe = socket.create_connection(("127.0.0.1", port), timeout=1)
                probe.close()
                leftover.append(port)
            except OSError:
                pass
        still_alive = guest is not None and guest.proc is not None \
            and guest.proc.poll() is None
        image_after = sha256_of(BOOT_IMAGE) if os.path.exists(BOOT_IMAGE) else "(gone)"
        moved = image_after != image_before

        print("[tls-suite] teardown: guest process still running: %s"
              % ("YES -- leak" if still_alive else "no"))
        print("[tls-suite] teardown: ports of mine still answering: %s"
              % (leftover or "none of mine"))
        print("[tls-suite] teardown: boot image sha256 after : %s%s"
              % (image_after, "   <-- CHANGED; this suite must never rebuild it"
                 if moved else "   (unchanged)"))

        failed = ledger.failed
        if still_alive:
            failed.append("the QEMU process outlived teardown")
        if leftover:
            failed.append("a port this suite owns is still live")
        if moved:
            failed.append("the boot image moved under this suite")

        # The guest's own words, on disk. Every claim this file prints is a slice of
        # this stream, and a run whose evidence cannot be re-read after it ended is a
        # run nobody can check.
        write_artifacts(peer, rows)

        # WHY a failed run keeps the directory: the generated CA, the peer's record of
        # each connection and the serial log are the whole evidence trail behind a
        # refusal, and deleting them turned a finding into a re-run from scratch. A
        # green run still leaves nothing behind.
        if failed or os.environ.get("TLS_SUITE_KEEP_ARTIFACTS") == "1":
            print("[tls-suite] teardown: artifacts kept under %s (%s)"
                  % (WORK_DIR, "the run did not pass" if failed
                     else "TLS_SUITE_KEEP_ARTIFACTS=1"))
        else:
            shutil.rmtree(WORK_DIR, ignore_errors=True)
            print("[tls-suite] teardown: work directory removed (%s)" % WORK_DIR)

        print("\n[tls-suite] %d checks, %d failed" % (len(ledger.rows), len(failed)))
        print("[tls-suite] evidence: QEMU-suite-verified against a LOCALLY-OPERATED CA "
              "(the four dials above). It does not by itself prove public-chain "
              "verification.")
        print("[tls-suite] public chain this run: %s"
              % notes.get("public", "not attempted (TLS_SUITE_PUBLIC=0, or the run "
                                    "did not reach that phase)"))
        print("[tls-suite] OVERALL: %s -- %s" % (
            "PASS" if not failed else "FAIL",
            "four dials on a local CA, teardown clean" if not failed
            else ", ".join(failed)))

        exit_code = 1 if failed else 0

    return exit_code


