def newest_source():
    """The newest `.rs` under `CURRENCY_SOURCES`, as `(mtime, path)`.

    WHY this is weighed against the image: the suite builds nothing, so a green run on
    an image that predates the sources its dials exercise would report yesterday's
    bytes as the current platform -- and that is exactly the run a changed verifier
    produces without anyone noticing.
    """
    newest, path = 0.0, None
    for entry in CURRENCY_SOURCES:
        if os.path.isfile(entry):
            candidates = [entry]
        else:
            candidates = [os.path.join(dirpath, name)
                          for dirpath, _, names in os.walk(entry)
                          for name in names if name.endswith(".rs")]
        for candidate in candidates:
            stamp = os.path.getmtime(candidate)
            if stamp > newest:
                newest, path = stamp, candidate
    return newest, path


