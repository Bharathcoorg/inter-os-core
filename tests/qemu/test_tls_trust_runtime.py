"""Device TLS trust, made reproducible: four dials on one boot.

Everything this suite claims, it claims from bytes the guest itself printed and
from what the peer on the other end of the socket observed. Nothing is taken from
the throwaway probes in `target/verify/`, which is where these handshakes used to
live -- and which is gitignored, so until this file existed no committed command
could reproduce a single device TLS verification.

WHAT IS UNDER TEST. The TLS client is not in the kernel: the handshake, the record
reader and the verifier live in `sdk/rust/interos-std/src/tls/`, reached through
syscalls 162/163, and the only userspace program that uses them is the browser. The
kernel holds the trust store (`kernel/src/crypto/tls_trust.rs`, RAM-only) and the
operator's console channel for it (`TLS_TRUST_BEGIN` / `TLS_TRUST_CHUNK` /
`TLS_TRUST_COMMIT` / `TLS_TRUST_REVOKE` in `kernel/src/serial.rs`). So the dial is
a real browser navigation, typed over the serial console, and the verdict is the
browser's own log line plus the peer's record of the connection.

THE FOUR DIALS, IN ORDER, IN ONE BOOT:

  1. refuse with no anchor -- a fresh device must not trust this peer, and the peer
     must see that (no handshake completed, no request reached it);
  2. install the root the peer's chain hangs from, and show the same dial accepted;
  3. carry real bytes over the verified channel -- asserted on the payload the
     browser read (`fetch_over_tcp bytes=<exactly what the peer sent>`, `trunc=0`,
     `err=0`, `decode: doc_len=<the document length this file chose>`), not on a
     handshake line;
  4. revoke the anchor and show the same dial refused again.

Dial 4 is the one that makes 2 and 3 mean something: without it, "accepted" could
be a hardcoded yes. With it the only difference between the refusals and the fetch
is the anchor in the store.

WHICH PEER -- READ THIS BEFORE TRUSTING A GREEN RUN. The four dials above run
against a LOCAL CA generated by this file into a throwaway directory, served by a
TLS 1.3 listener on the host loopback that the guest reaches as 10.0.2.2 through
QEMU's user-mode network. That is a locally-operated certificate authority, not a
public one: it proves the store is the thing the verifier judges with, and it proves
the walk reaches a root the operator chose -- it does NOT prove that the certificate
of any real site on the internet verifies. A suite that went green while implying
public-Internet verification would be worse than no suite, so this file prints the
distinction on every run and names it in its final status line.

A public-chain phase runs after the four dials when the environment allows it
(`TLS_SUITE_PUBLIC=0` turns it off): install the committed public fixture ISRG Root
X1, dial https://developer.mozilla.org/en-US/ and report what arrived. It is
reported, not gated, because it depends on this host's Internet path and on today's
public chains still sitting under that root -- a fixture that can move without
anything in the platform changing. Its outcome is printed per line, and a public
dial that does not carry bytes is printed as NOT VERIFIED with the reason. A green
OVERALL line therefore always refers to the four local dials; the public line says
for itself whether public-chain verification happened in this run.

WHY THE CHAIN IS P-384 OVER P-256: public ECDSA chains arrive as a secp384r1 issuer
above a prime256v1 leaf, so the anchor has to be reachable through a curve the
verifier had never been handed before. A root the console can carry is a small root
(`MAX_ANCHOR_DER_BYTES` is 2048 and one console chunk is 120 bytes), so this CA is
built with a short common name and no auxiliary extensions -- the point is the
install path, not the paperwork.

WHY THE URL IS AN ADDRESS AND NOT A NAME: the only listener this suite can offer the
guest lives on this host's loopback, and under QEMU's user-mode network that loopback
is 10.0.2.2, so the dial types that literal. It is the dial that invents nothing: the
reference identity is the address the socket really was opened against, and RFC 6125
(section 6) judges an address identity against the certificate's iPAddress entries --
which is what the chain this file mints carries, so the install dial has a name in it
to match. The same rule means the ClientHello carries no server_name (RFC 6066 forbids
a literal address there), so the walk reaches the verifier with nothing advertised on
the wire -- a thing a name-shaped dial cannot exercise at all.
The name dial is kept one environment variable away (`TLS_SUITE_HOST=tls.test`) and is
honestly blocked: the browser stopped mapping a name nobody resolved onto the SLIRP
gateway, so that run prints the guest's own "The host name was not resolved" sentence
and names the knob above instead of timing out silently. A green OVERALL line therefore
means address-identity verification against an installed anchor, and the printed peer
line says which host this run dialled.

ISOLATION. This run owns serial 5641 and monitor 5642 (the runtime suites already hold
5558-5563 and 5565, 5571/5572, 5575/5576, 5585, 5591/5592, 5593 and 5595/5596, plus
43551/44551 for `tests/qemu/interaction_x86.py`) and its own TLS peer on
127.0.0.1:8461, and it opens no Studio or QMP endpoint. It attaches its own throwaway
data disk under `target/verify/tls_suite/` -- overridable with `DATA_DISK_PATH`, which
refuses to point at the 6 GiB master -- and boots with `snapshot=on` on both drives so
the boot image and the disk it was given both stay exactly as they were found. It
builds nothing, and it never rewrites `target/inter-os-bios.img`: the image already on
disk is the thing under test, and its sha256 is printed before and after to show it did
not move. Because it builds nothing, it says what it is booting: the newest mtime among
the TLS client, the kernel's trust store and console channel, and the browser is
weighed against the image, and an image older than the sources its dials exercise stops
the run before a guest boots rather than quietly certifying yesterday's bytes as
today's platform (`TLS_SUITE_ALLOW_STALE_IMAGE=1` turns that stop into a labelled
warning printed beside the dials).

NO RETENTION. The generated CA key, the leaf key, the response bytes captured at the
peer and the data disk all live in one directory under `target/verify/`, which is
gitignored, and the guest's serial transcript is written there too. A green run deletes
the directory on the way out; a run that failed keeps it and prints where, because a
refusal you destroyed the evidence for is not a finding. `TLS_SUITE_KEEP_ARTIFACTS=1`
keeps it either way for a debug session. Only the root's PUBLIC DER is ever sent to the
guest. Nothing this run produces lands in a tracked file.

HOW TO RUN:

    python tests/qemu/test_tls_trust_runtime.py
    TLS_SUITE_BREAK=skip-install python tests/qemu/test_tls_trust_runtime.py   # must FAIL
    TLS_SUITE_HOST=tls.test python tests/qemu/test_tls_trust_runtime.py        # name dial (blocked: nothing resolves it)
    TLS_SUITE_PUBLIC=0 python tests/qemu/test_tls_trust_runtime.py             # skip the reported public phase

Requires QEMU, a host Python with `cryptography` and an idle port band; prints SKIP
and exits 0 when QEMU is not on this machine, exactly like the other `tests/qemu/`
suites. It needs a live guest, so `tests/run_all_contracts.py` skips it.
"""

