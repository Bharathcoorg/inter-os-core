def build_chain(directory):
    """A secp384r1 root above a prime256v1 leaf, generated fresh into `directory`.

    RETURNS (fullchain_pem, leaf_key_pem, root_der) paths. The private halves are
    written inside the throwaway work directory this suite deletes; only the root's
    public DER is ever handed to the guest.
    """
    import datetime
    import ipaddress

    from cryptography import x509
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.x509.oid import NameOID

    os.makedirs(directory, exist_ok=True)
    ca_key_path = os.path.join(directory, "suite-ca.key")
    ca_pem_path = os.path.join(directory, "suite-ca.pem")
    root_der_path = os.path.join(directory, "suite-ca-root.der")
    leaf_key_path = os.path.join(directory, "suite-leaf.key")
    chain_path = os.path.join(directory, "suite-leaf-chain.pem")

    ca_key = ec.generate_private_key(ec.SECP384R1())
    leaf_key = ec.generate_private_key(ec.SECP256R1())
    now = datetime.datetime.now(datetime.timezone.utc)
    ca_name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "InterOS suite root")])

    ca_cert = (
        x509.CertificateBuilder()
        .subject_name(ca_name)
        .issuer_name(ca_name)
        .public_key(ca_key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(days=1))
        .not_valid_after(now + datetime.timedelta(days=365))
        .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
        .sign(ca_key, hashes.SHA384())
    )

    # Every identity the guest might dial: this host's loopback under both names
    # QEMU's user-mode networking gives it, and the knob's own value, so the
    # reference identity matches whichever one this suite types into the bar.
    identities = ["127.0.0.1", GATEWAY_ADDRESS, "tls.test"]
    if DIAL_HOST not in identities:
        identities.append(DIAL_HOST)
    subject_alt = []
    for identity in identities:
        try:
            subject_alt.append(x509.IPAddress(ipaddress.ip_address(identity)))
        except ValueError:
            subject_alt.append(x509.DNSName(identity))

    leaf_name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, GATEWAY_ADDRESS)])
    leaf = (
        x509.CertificateBuilder()
        .subject_name(leaf_name)
        .issuer_name(ca_name)
        .public_key(leaf_key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(days=1))
        .not_valid_after(now + datetime.timedelta(days=30))
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .add_extension(x509.SubjectAlternativeName(subject_alt), critical=False)
        .sign(ca_key, hashes.SHA384())
    )

    with open(ca_key_path, "wb") as fh:
        fh.write(ca_key.private_bytes(serialization.Encoding.PEM,
                                      serialization.PrivateFormat.PKCS8,
                                      serialization.NoEncryption()))
    with open(ca_pem_path, "wb") as fh:
        fh.write(ca_cert.public_bytes(serialization.Encoding.PEM))
    with open(root_der_path, "wb") as fh:
        fh.write(ca_cert.public_bytes(serialization.Encoding.DER))
    with open(leaf_key_path, "wb") as fh:
        fh.write(leaf_key.private_bytes(serialization.Encoding.PEM,
                                        serialization.PrivateFormat.PKCS8,
                                        serialization.NoEncryption()))
    # The peer sends leaf then root, so the walk is handed the entry point and the
    # link to install: an anchor only present in the store would leave nothing to
    # place at the trust-anchor position.
    with open(chain_path, "wb") as fh:
        fh.write(leaf.public_bytes(serialization.Encoding.PEM))
        fh.write(ca_cert.public_bytes(serialization.Encoding.PEM))
    return chain_path, leaf_key_path, root_der_path


def make_document(size=DOCUMENT_BYTES):
    """An HTML document of exactly `size` bytes, carrying a marker in its body."""
    head = (b"<!doctype html><html><head><meta charset=\"utf-8\">"
            b"<title>InterOS TLS suite</title></head><body><h1>marker:")
    tail = b"</h1><p>the record made it back over the verified channel</p></body></html>"
    filler = b"interos-tls-suite-padding."
    page = head + DOC_MARKER + tail
    while len(page) < size:
        page += filler
    return page[:size]


def make_answer(document):
    """The exact HTTP response this peer puts on the verified channel."""
    head = (b"HTTP/1.1 200 OK\r\nContent-Type: text/html\r\nContent-Length: %d\r\n"
            b"Connection: close\r\n\r\n" % len(document))
    return head + document, len(head)


class LocalPeer:
    """One loopback TLS 1.3 listener that records what each connection reached.

    Bound to 127.0.0.1 only, so nothing outside this machine can connect to it. Each
    connection appends exactly one record once it resolves: either an immediate
    refusal (the client broke off before the keys changed) or a completed handshake
    with the plaintext request the client sent. The refusal case is the witness that
    dial 1 and dial 4 are refusals at the verifier and not a socket that never
    opened.
    """

    def __init__(self, port=PEER_PORT, hold_seconds=45.0, linger=3.0):
        self.port = port
        self.hold_seconds = hold_seconds
        self.linger = linger
        self.answer = b""
        self.records = []
        self.root_der_path = None
        self._stop = threading.Event()
        self._thread = None
        self._server = None
        self._context = None

    def set_answer(self, answer):
        self.answer = answer

    def _handler_factory(self):
        hold = self.hold_seconds
        linger = self.linger
        peer = self

        class Handler(socketserver.BaseRequestHandler):
            def handle(self):
                record = {"peer": str(self.client_address), "at": round(time.time(), 2)}
                try:
                    wrapped = peer._context.wrap_socket(self.request, server_side=True)
                except ssl.SSLError as exc:
                    record["handshake"] = "refused: %s" % exc
                    peer.records.append(record)
                    return
                except (ConnectionResetError, BrokenPipeError, OSError) as exc:
                    record["handshake"] = "reset before keys: %r" % exc
                    peer.records.append(record)
                    return
                record["handshake"] = "completed"
                try:
                    cipher = wrapped.cipher()
                    record["negotiated"] = {"version": wrapped.version(),
                                            "cipher": list(cipher or ())}
                except Exception as exc:  # pragma: no cover - diagnostic only
                    record["negotiated"] = "unavailable: %r" % exc
                try:
                    wrapped.settimeout(hold)
                    data = wrapped.recv(2048)
                    record["request"] = data[:200].decode("latin-1")
                    if data:
                        wrapped.sendall(peer.answer)
                        if linger:
                            time.sleep(linger)
                except Exception as exc:
                    record["after_keys"] = "%r" % exc
                finally:
                    try:
                        wrapped.close()
                    except Exception:
                        pass
                peer.records.append(record)

        return Handler

    def start(self):
        chain_path, key_path, self.root_der_path = build_chain(WORK_DIR)
        size = os.path.getsize(self.root_der_path)
        if size > MAX_ANCHOR_DER_BYTES:
            raise RuntimeError(
                "the generated root is %d bytes, past the %d the kernel store holds"
                % (size, MAX_ANCHOR_DER_BYTES))
        self._context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        self._context.load_cert_chain(chain_path, key_path)
        self._context.minimum_version = ssl.TLSVersion.TLSv1_3

        class Server(socketserver.ThreadingTCPServer):
            allow_reuse_address = True
            daemon_threads = True

        self._server = Server((PEER_HOST, self.port), self._handler_factory())
        self._server.timeout = 0.5
        self._thread = threading.Thread(target=self._loop, daemon=True)
        self._thread.start()
        return self

    def _loop(self):
        while not self._stop.is_set():
            try:
                self._server.handle_request()
            except OSError:
                return

    def stop(self):
        self._stop.set()
        if self._server:
            try:
                self._server.server_close()
            except Exception:
                pass
        if self._thread:
            self._thread.join(timeout=4)

    def newest(self):
        return self.records[-1] if self.records else None

    def wait_for_record(self, before, budget=25.0):
        deadline = time.time() + budget
        while time.time() < deadline:
            if len(self.records) > before:
                return self.records[before]
            time.sleep(0.2)
        return None


