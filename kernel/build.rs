//! Declares the kernel's real build inputs.
//!
//! `src/task/images.rs` embeds the first-party Ring-3 user images with
//! `include_bytes!`. Cargo does not track files reached through `include_bytes!`,
//! so without this the kernel would keep whatever bytes were on disk when it was
//! last compiled and silently ship a stale launcher, compositor or service after
//! its source changed. Emitting `rerun-if-changed` for every embedded image makes
//! that dependency explicit.
//!
//! WHY the list must be exactly the embedded set, and not merely a superset:
//! `rerun-if-changed` for a path that does not exist makes cargo dirty the crate
//! on every build -- it cannot fingerprint what it cannot stat. An entry for an
//! image that was removed therefore costs a full kernel recompile on every
//! no-op rebuild, while a missing entry lets an edited image ship the bytes the
//! previous build embedded. Both are silent, and both are this list's only job.

use std::path::Path;

/// The boot integrity profile a build runs under when `INTEROS_BOOT_POLICY`
/// says nothing.
///
/// WHY the default is the strict profile: an image that cannot say which
/// profile it enforces is an image whose behaviour is a guess, and the strict
/// profile is the one that refuses to bring protected objects up when they
/// do not authenticate. A developer who wants the permissive profile asks
/// for it by name.
const DEFAULT_BOOT_POLICY: &str = "verified";

/// The token of the profile that refuses activation when authentication fails.
const BOOT_POLICY_VERIFIED: &str = "verified";

/// The token of the profile that boots and reports an authentication failure.
const BOOT_POLICY_UNVERIFIED_DEVELOPMENT: &str = "unverified-development";

/// Every user image embedded by `src/task/images.rs`, keyed by output file name.
const EMBEDDED_USER_IMAGES: &[&str] = &[
    "init",
    "settings",
    "displayd",
    "inputd",
    "storaged",
    "netd",
    "powerd",
    "modemd",
    "audiod",
    "camerad",
    "sensord",
    "compositor",
    "launcher",
    "dialer",
    "vault",
    "camera",
    "calculator",
    "browser",
    "messages",
    "calendar",
    "music",
    "file_manager",
    "gallery",
    "notes",
    "agent_manager",
    "video_player",
    "webview_demo",
    "aid",
    "searchd",
    "agentd",
    "acrd",
    "acr-app-runtime",
];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=INTEROS_BUILD_GIT_SHA");
    println!("cargo:rerun-if-env-changed=INTEROS_BUILD_GIT_DIRTY");
    println!("cargo:rerun-if-env-changed=INTEROS_BOOT_POLICY");
    println!("cargo:rerun-if-changed=../.git/HEAD");

    let manifest_dir = match std::env::var("CARGO_MANIFEST_DIR") {
        Ok(dir) => Path::new(&dir).to_path_buf(),
        Err(_) => return,
    };
    let user_target = manifest_dir.join("..").join("target").join("x86_64-unknown-none").join("debug");

    for image in EMBEDDED_USER_IMAGES {
        let path = user_target.join(image);
        // Track the path whether or not it exists yet, so creating a missing
        // image later also triggers a rebuild.
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let missing: Vec<&str> = EMBEDDED_USER_IMAGES
        .iter()
        .filter(|image| !user_target.join(image).exists())
        .copied()
        .collect();
    if !missing.is_empty() {
        panic!(
            "unreadable or absent build input: embedded user images missing from {}: {} (run tools/build_userspace.ps1)",
            user_target.display(),
            missing.join(", ")
        );
    }

    // Verify manifest has no duplicate names
    let mut seen_names = std::collections::HashSet::new();
    for name in EMBEDDED_USER_IMAGES {
        if !seen_names.insert(*name) {
            panic!("duplicate embedded image name in manifest: {}", name);
        }
    }

    let out_dir = match std::env::var("OUT_DIR") {
        Ok(dir) => Path::new(&dir).to_path_buf(),
        Err(_) => return,
    };

    use sha2::{Digest, Sha256};
    let mut digests_code = String::from("// Auto-generated by kernel build.rs - DO NOT EDIT\n");
    digests_code.push_str("pub static EXPECTED_IMAGE_DIGESTS: &[(&str, [u8; 32])] = &[\n");
    let mut manifest_hasher = Sha256::new();
    let mut json_images = Vec::new();
    for image in EMBEDDED_USER_IMAGES {
        let path = user_target.join(image);
        let bytes = std::fs::read(&path).unwrap_or_else(|e| {
            panic!("unreadable build input at {}: {}", path.display(), e);
        });
        let digest: [u8; 32] = Sha256::digest(&bytes).into();
        if digest == [0u8; 32] {
            panic!("computed all-zero digest for embedded image {}", image);
        }
        // WHY the aggregate hashes the NAME next to the digest: a manifest that
        // carried only digests could not say which image a digest belonged to,
        // and two images with the same bytes would be indistinguishable. This
        // is the build-time encoding and nothing else uses it -- the runtime
        // system-inventory digest (kernel/src/storage/verified.rs) covers
        // different data with a different, length-prefixed encoding, so the
        // two values are never equal and never compared.
        manifest_hasher.update(image.as_bytes());
        manifest_hasher.update(&digest);
        let mut hex = String::with_capacity(64);
        for b in &digest {
            hex.push_str(&format!("{:02x}", b));
        }
        json_images.push(format!("    \"{}\": {{\"sha256\": \"{}\", \"size\": {}}}", image, hex, bytes.len()));
        digests_code.push_str(&format!("    (\"{}\", {:?}),\n", image, digest));
    }
    digests_code.push_str("];\n");
    let digests_path = out_dir.join("embedded_image_digests.rs");
    std::fs::write(&digests_path, digests_code).expect("failed to write embedded_image_digests.rs");

    // WHY this value is named an IMAGE manifest digest: it is the digest OF
    // the build-time embedded-image manifest -- the concatenation of, for
    // each embedded Ring-3 image in build order, the image name bytes
    // followed by the 32 raw bytes of that image's SHA-256 digest. It is NOT
    // the runtime system-inventory digest the kernel arms at boot: that one
    // covers the VFS's read-only objects with a length-prefixed encoding, so
    // the two are different values over different data.
    let embedded_image_manifest_sha256: [u8; 32] = manifest_hasher.finalize().into();
    let mut manifest_hex = String::with_capacity(64);
    for b in &embedded_image_manifest_sha256 {
        manifest_hex.push_str(&format!("{:02x}", b));
    }

    let git_sha = std::env::var("INTEROS_BUILD_GIT_SHA").unwrap_or_else(|_| {
        std::process::Command::new("git")
            .args(["rev-parse", "HEAD"])
            .output()
            .ok()
            .and_then(|o| String::from_utf8(o.stdout).ok())
            .map(|s| s.trim().to_string())
            .unwrap_or_else(|| "unknown".to_string())
    });

    let git_dirty = std::env::var("INTEROS_BUILD_GIT_DIRTY")
        .map(|v| v == "1" || v == "true")
        .unwrap_or_else(|_| {
            std::process::Command::new("git")
                .args(["status", "--porcelain"])
                .output()
                .ok()
                .and_then(|o| String::from_utf8(o.stdout).ok())
                .map(|s| !s.trim().is_empty())
                .unwrap_or(false)
        });

    let profile = std::env::var("PROFILE").unwrap_or_else(|_| "release".to_string());
    let debug_cp = std::env::var("CARGO_FEATURE_DEBUG_CONTROL_PLANE").is_ok();

    // WHY the profile is a build input and not a runtime flag: an image that
    // ships the Verified profile must not be talked out of it by anything the
    // device can write. The profile therefore names what the image was built
    // to enforce; the only freedom left at boot is a request for the stricter
    // profile, which a development build accepts and a verified build refuses
    // (see `kernel/src/storage/verified.rs`).
    let boot_policy = std::env::var("INTEROS_BOOT_POLICY")
        .unwrap_or_else(|_| DEFAULT_BOOT_POLICY.to_string())
        .trim()
        .to_ascii_lowercase();
    if boot_policy != BOOT_POLICY_VERIFIED && boot_policy != BOOT_POLICY_UNVERIFIED_DEVELOPMENT {
        panic!(
            "INTEROS_BOOT_POLICY must be '{}' or '{}', got '{}'",
            BOOT_POLICY_VERIFIED, BOOT_POLICY_UNVERIFIED_DEVELOPMENT, boot_policy
        );
    }
    // The kernel library reads the same token, so the build default is one
    // value in one place rather than a constant the boot path could disagree
    // with.
    println!("cargo:rustc-env=INTEROS_BOOT_POLICY={}", boot_policy);

    let mut prov_code = String::from("// Auto-generated by kernel build.rs - DO NOT EDIT\n");
    prov_code.push_str(&format!("pub static BUILD_GIT_SHA: &str = \"{}\";\n", git_sha));
    prov_code.push_str(&format!("pub static BUILD_GIT_DIRTY: bool = {};\n", git_dirty));
    prov_code.push_str(&format!("pub static BUILD_PROFILE: &str = \"{}\";\n", profile));
    prov_code.push_str(&format!("pub static BUILD_DEBUG_CONTROL_PLANE: bool = {};\n", debug_cp));
    prov_code.push_str(&format!("pub static BUILD_BOOT_POLICY: &str = \"{}\";\n", boot_policy));
    prov_code.push_str(&format!(
        "pub static EMBEDDED_IMAGE_MANIFEST_SHA256: [u8; 32] = {:?};\n",
        embedded_image_manifest_sha256
    ));
    let prov_path = out_dir.join("build_provenance.rs");
    std::fs::write(&prov_path, prov_code).expect("failed to write build_provenance.rs");

    let json_content = format!(
        "{{\n  \"embedded_image_manifest_sha256\": \"{}\",\n  \"digest_scope\": \"sha256 over concat(image_name || raw_sha256_digest) for each embedded Ring-3 image, in build.rs order -- the BUILD-TIME embedded-image manifest digest; not the runtime system-inventory digest\",\n  \"count\": {},\n  \"images\": {{\n{}\n  }}\n}}\n",
        manifest_hex,
        EMBEDDED_USER_IMAGES.len(),
        json_images.join(",\n")
    );
    let json_path = out_dir.join("embedded_image_digests.json");
    std::fs::write(&json_path, json_content).expect("failed to write embedded_image_digests.json");
}
