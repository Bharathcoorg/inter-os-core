/// High-definition anti-aliased text renderer driven by true glyph coverage.
///
/// Each glyph cell carries a 4-bit coverage level 0..=15 (see [`FONT_COV`]).
/// Level 0 is transparent, level 15 is solid ink, and levels 1..=14 blend
/// `color` toward `bg` with alpha `level * 17` -- a sixteen-step ramp, which is
/// what keeps a glyph edge from contouring into visible bands. Because the
/// coverage comes from the same supersampled raster the 1-bit tables threshold,
/// edges land on intermediate tones exactly where the outline crosses the pixel
/// instead of stair-stepping, which is what makes text read as type rather than
/// as blocks. Integer `scale` upscales the covered glyph with nearest neighbour:
/// the source pixels are anti-aliased, the magnification stays sharp.
#[inline(always)]
pub fn test_text_aa(
    x: usize,
    y: usize,
    x0: usize,
    y0: usize,
    scale: usize,
    text: &[u8],
    color: u32,
    bg: u32,
    bold: bool,
) -> Option<u32> {
    if scale == 0 || text.is_empty() {
        return None;
    }
    let dy = y.checked_sub(y0)?;
    let row = dy / scale;
    if row >= GLYPH_H {
        return None;
    }
    let dx = x.checked_sub(x0)?;
    let mut pen = 0usize;
    for &c in text {
        let adv = advance_of(c, bold) * scale;
        if dx < pen + adv {
            let col = (dx - pen) / scale;
            match coverage(c, col, row, bold) {
                0 => return None,
                15 => return Some(color),
                level => return Some(blend(color, bg, (level * 17) as u8)),
            }
        }
        pen += adv;
    }
    None
}

/// Truncates `text` with an ellipsis ("...") if it exceeds `max_w` at `scale`.
/// Writes into `out_buf` and returns the number of bytes written.
pub fn ellipsize<'a>(text: &[u8], scale: usize, max_w: usize, out_buf: &mut [u8]) -> usize {
    if text.is_empty() {
        return 0;
    }
    let total_w = measure(text, scale);
    if total_w <= max_w {
        let len = text.len().min(out_buf.len());
        out_buf[..len].copy_from_slice(&text[..len]);
        return len;
    }

    let dots = b"...";
    let dots_w = measure(dots, scale);
    if dots_w > max_w || out_buf.len() < 3 {
        return 0;
    }

    let budget = max_w - dots_w;
    let mut current_w = 0usize;
    let mut fit_len = 0usize;

    for (i, &c) in text.iter().enumerate() {
        let adv = advance_of(c, false) * scale;
        if current_w + adv > budget || fit_len + 3 > out_buf.len() {
            break;
        }
        current_w += adv;
        fit_len = i + 1;
    }

    out_buf[..fit_len].copy_from_slice(&text[..fit_len]);
    out_buf[fit_len..fit_len + 3].copy_from_slice(dots);
    fit_len + 3
}

/// Splits `text` into at most `max_lines` line byte slices, breaking at spaces when possible.
pub fn wrap_text<'a>(
    text: &'a [u8],
    scale: usize,
    max_w: usize,
    max_lines: usize,
    out_lines: &mut [&'a [u8]],
) -> usize {
    if text.is_empty() || max_lines == 0 || out_lines.is_empty() {
        return 0;
    }
    let mut line_count = 0;
    let mut start = 0;
    let n = text.len();

    while start < n && line_count < max_lines && line_count < out_lines.len() {
        while start < n && text[start] == b' ' {
            start += 1;
        }
        if start >= n {
            break;
        }

        let mut end = start;
        let mut last_break = None;
        let mut cur_w = 0usize;

        while end < n {
            let c = text[end];
            let adv = advance_of(c, false) * scale;
            if cur_w + adv > max_w && end > start {
                break;
            }
            cur_w += adv;
            if c == b' ' {
                last_break = Some(end);
            }
            end += 1;
        }

        let line_end = if end >= n {
            n
        } else if let Some(brk) = last_break {
            brk
        } else {
            end
        };

        out_lines[line_count] = &text[start..line_end];
        line_count += 1;
        start = line_end;
    }

    line_count
}

/// Renders a text pixel with optional clipping rectangle (x_min, y_min, x_max, y_max).
#[inline(always)]
pub fn test_text_clipped(
    x: usize,
    y: usize,
    x0: usize,
    y0: usize,
    scale: usize,
    text: &[u8],
    color: u32,
    clip: Option<(usize, usize, usize, usize)>,
) -> Option<u32> {
    if let Some((cx0, cy0, cx1, cy1)) = clip {
        if x < cx0 || x >= cx1 || y < cy0 || y >= cy1 {
            return None;
        }
    }
    test_text(x, y, x0, y0, scale, text, color)
}

