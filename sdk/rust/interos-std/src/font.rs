#[inline]
pub fn glyph_index(c: u8) -> Option<usize> {
    if (FIRST_CHAR..=LAST_CHAR).contains(&c) {
        Some((c - FIRST_CHAR) as usize)
    } else {
        None
    }
}

#[inline]
pub fn advance_of(c: u8, bold: bool) -> usize {
    match glyph_index(c) {
        Some(i) => {
            if bold {
                ADVANCE_BOLD[i] as usize
            } else {
                ADVANCE[i] as usize
            }
        }
        None => FALLBACK_ADVANCE,
    }
}

#[inline]
pub fn glyph_rows(c: u8, bold: bool) -> Option<&'static [u16]> {
    let i = glyph_index(c)?;
    let table: &[u16] = if bold { &FONT_BOLD } else { &FONT };
    Some(&table[i * GLYPH_H..i * GLYPH_H + GLYPH_H])
}

#[inline]
pub fn pixel(c: u8, col: usize, row: usize, bold: bool) -> bool {
    if col >= GLYPH_W || row >= GLYPH_H {
        return false;
    }
    match glyph_rows(c, bold) {
        Some(rows) => (rows[row] >> (GLYPH_W - 1 - col)) & 1 == 1,
        None => false,
    }
}

/// Coverage of the glyph pixel at `(col, row)` as a 4-bit level 0..=15.
///
/// This is the anti-aliasing source: `test_text_aa` blends `color` toward `bg`
/// with `level * 17` alpha, a sixteen-step ramp, so glyph edges land on
/// intermediate tones instead of on hard on/off pixels. The binary view is
/// `level >= 8`, which is exactly `pixel` and matches the 1-bit threshold the
/// generator bakes into `FONT` and `FONT_BOLD`, so layout maths and rendering
/// cannot disagree about ink.
#[inline]
pub fn coverage(c: u8, col: usize, row: usize, bold: bool) -> u32 {
    if col >= GLYPH_W || row >= GLYPH_H {
        return 0;
    }
    let table: &[u64] = if bold { &FONT_COV_BOLD } else { &FONT_COV };
    match glyph_index(c) {
        Some(i) => ((table[i * GLYPH_H + row] >> (4 * (GLYPH_W - 1 - col))) & 0xF) as u32,
        None => 0,
    }
}

#[inline]
pub fn measure(text: &[u8], scale: usize) -> usize {
    let mut w = 0usize;
    for &c in text {
        w += advance_of(c, false) * scale;
    }
    w
}

#[inline]
pub fn measure_bold(text: &[u8], scale: usize) -> usize {
    let mut w = 0usize;
    for &c in text {
        w += advance_of(c, true) * scale;
    }
    w
}

#[inline]
pub fn line_height(scale: usize) -> usize {
    GLYPH_H * scale
}

#[inline]
pub fn center_x(text: &[u8], scale: usize, available: usize) -> usize {
    let w = measure(text, scale);
    if w >= available {
        0
    } else {
        (available - w) / 2
    }
}

#[inline(always)]
pub fn blend(fg: u32, bg: u32, alpha: u8) -> u32 {
    if alpha == 255 {
        return fg;
    }
    if alpha == 0 {
        return bg;
    }
    let a = alpha as u32;
    let inv_a = 255 - a;
    let fr = (fg >> 16) & 0xFF;
    let fg_c = (fg >> 8) & 0xFF;
    let fb = fg & 0xFF;

    let br = (bg >> 16) & 0xFF;
    let bg_c = (bg >> 8) & 0xFF;
    let bb = bg & 0xFF;

    // Optical gamma-correct blending (gamma ≈ 2.0 luminous square curve)
    // Eliminates dark fringes and crushed midtones on OLED and high-DPI panels
    let r2 = (fr * fr * a + br * br * inv_a) / 255;
    let g2 = (fg_c * fg_c * a + bg_c * bg_c * inv_a) / 255;
    let b2 = (fb * fb * a + bb * bb * inv_a) / 255;

    let r = r2.isqrt() as u8;
    let g = g2.isqrt() as u8;
    let b = b2.isqrt() as u8;

    0xFF00_0000 | ((r as u32) << 16) | ((g as u32) << 8) | (b as u32)
}

/// Standard proportional text hit-test returning solid ink color if hit.
#[inline(always)]
pub fn test_text(
    x: usize,
    y: usize,
    x0: usize,
    y0: usize,
    scale: usize,
    text: &[u8],
    color: u32,
) -> Option<u32> {
    if scale == 0 || text.is_empty() {
        return None;
    }
    let dy = y.checked_sub(y0)?;
    let row = dy / scale;
    if row >= GLYPH_H {
        return None;
    }
    let dx = x.checked_sub(x0)?;
    let mut pen = 0usize;
    for &c in text {
        let adv = advance_of(c, false) * scale;
        if dx < pen + adv {
            let col = (dx - pen) / scale;
            return if pixel(c, col, row, false) {
                Some(color)
            } else {
                None
            };
        }
        pen += adv;
    }
    None
}

