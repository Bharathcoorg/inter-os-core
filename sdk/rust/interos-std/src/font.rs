pub fn center_x(text: &[u8], scale: usize, available: usize) -> usize {
    let w = measure(text, scale);
    if w >= available {
        0
    } else {
        (available - w) / 2
    }
}

#[inline(always)]
pub fn blend(fg: u32, bg: u32, alpha: u8) -> u32 {
    if alpha == 255 {
        return fg;
    }
    if alpha == 0 {
        return bg;
    }
    let a = alpha as u32;
    let inv_a = 255 - a;
    let fr = (fg >> 16) & 0xFF;
    let fg_c = (fg >> 8) & 0xFF;
    let fb = fg & 0xFF;

    let br = (bg >> 16) & 0xFF;
    let bg_c = (bg >> 8) & 0xFF;
    let bb = bg & 0xFF;

    let r = (fr * a + br * inv_a) / 255;
    let g = (fg_c * a + bg_c * inv_a) / 255;
    let b = (fb * a + bb * inv_a) / 255;

    0xFF00_0000 | (r << 16) | (g << 8) | b
}

/// Standard proportional text hit-test returning solid ink color if hit.
#[inline(always)]
pub fn test_text(
    x: usize,
    y: usize,
    x0: usize,
    y0: usize,
    scale: usize,
    text: &[u8],
    color: u32,
) -> Option<u32> {
    if scale == 0 || text.is_empty() {
        return None;
    }
    let dy = y.checked_sub(y0)?;
    let row = dy / scale;
    if row >= GLYPH_H {
        return None;
    }
    let dx = x.checked_sub(x0)?;
    let mut pen = 0usize;
    for &c in text {
        let adv = advance_of(c, false) * scale;
        if dx < pen + adv {
            let col = (dx - pen) / scale;
            return if pixel(c, col, row, false) {
                Some(color)
            } else {
                None
            };
        }
        pen += adv;
    }
    None
}

