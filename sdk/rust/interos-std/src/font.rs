    #[test]
    fn test_coverage_agrees_with_pixel() {
        // The binary ink view is `coverage >= 2` by construction (the 2-bit
        // levels quantise the same supersampled source the 1-bit tables
        // threshold at 0.5), so layout maths (`pixel`) and rendering
        // (`test_text_aa`) can never disagree about what is ink.
        for c in FIRST_CHAR..=LAST_CHAR {
            for row in 0..GLYPH_H {
                for col in 0..GLYPH_W {
                    for bold in [false, true] {
                        let ink = pixel(c, col, row, bold);
                        let level = coverage(c, col, row, bold);
                        assert!(level <= 3, "coverage level out of range");
                        assert_eq!(ink, level >= 2,
                            "pixel/coverage disagree at {:?} col {} row {} bold {}",
                            c as char, col, row, bold);
                    }
                }
            }
        }
    }

    #[test]
    fn test_aa_uses_intermediate_tones() {
        // Proves the coverage tables carry real edge data: at least one cell
        // in the face must sit at a partial level, and the blitter must turn
        // it into a blend rather than a hard on/off pixel.
        let mut partials = 0u32;
        for c in FIRST_CHAR..=LAST_CHAR {
            for row in 0..GLYPH_H {
                for col in 0..GLYPH_W {
                    match coverage(c, col, row, false) {
                        1 | 2 => partials += 1,
                        _ => {}
                    }
                }
            }
        }
        assert!(partials > 0, "face has no anti-aliased edge cells");
        // Spot-check the blend mapping level*85 on a known partial cell.
        let mut checked = false;
        for c in FIRST_CHAR..=LAST_CHAR {
            for row in 0..GLYPH_H {
                for col in 0..GLYPH_W {
                    let level = coverage(c, col, row, false);
                    if level == 1 || level == 2 {
                        let fg = 0xFFFFFFFF;
                        let bg = 0xFF000000;
                        let got = blend(fg, bg, (level * 85) as u8);
                        assert_ne!(got, fg);
                        assert_ne!(got, bg);
                        checked = true;
                        break;
                    }
                }
                if checked {
                    break;
                }
            }
            if checked {
                break;
            }
        }
        assert!(checked);
    }

