    fn test_coverage_agrees_with_pixel() {
        // The binary ink view is `coverage >= 8` by construction (the 4-bit
        // levels quantise the same supersampled source the 1-bit tables
        // threshold at 0.5), so layout maths (`pixel`) and rendering
        // (`test_text_aa`) can never disagree about what is ink.
        for c in FIRST_CHAR..=LAST_CHAR {
            for row in 0..GLYPH_H {
                for col in 0..GLYPH_W {
                    for bold in [false, true] {
                        let ink = pixel(c, col, row, bold);
                        let level = coverage(c, col, row, bold);
                        assert!(level <= 15, "coverage level out of range");
                        assert_eq!(ink, level >= 8,
                            "pixel/coverage disagree at {:?} col {} row {} bold {}",
                            c as char, col, row, bold);
                    }
                }
            }
        }
    }

    #[test]
    fn test_aa_uses_intermediate_tones() {
        // Proves the coverage tables carry real edge data: the face must hold
        // cells across a wide span of the 16-step ramp -- not merely one or two
        // partial tones -- and the blitter must turn them into blends rather
        // than hard on/off pixels.
        let mut partials = 0u32;
        let mut distinct = [false; 16];
        for c in FIRST_CHAR..=LAST_CHAR {
            for row in 0..GLYPH_H {
                for col in 0..GLYPH_W {
                    let level = coverage(c, col, row, false) as usize;
                    if level != 0 && level != 15 {
                        partials += 1;
                        distinct[level] = true;
                    }
                }
            }
        }
        assert!(partials > 0, "face has no anti-aliased edge cells");
        let tones = distinct.iter().filter(|&&d| d).count();
        assert!(tones >= 6,
            "only {} distinct edge tones; a 16-step ramp should span many more",
            tones);
        // Spot-check the blend mapping level*17 on a known partial cell.
        let mut checked = false;
        for c in FIRST_CHAR..=LAST_CHAR {
            for row in 0..GLYPH_H {
                for col in 0..GLYPH_W {
                    let level = coverage(c, col, row, false);
                    if level != 0 && level != 15 {
                        let fg = 0xFFFFFFFF;
                        let bg = 0xFF000000;
                        let got = blend(fg, bg, (level * 17) as u8);
                        assert_ne!(got, fg);
                        assert_ne!(got, bg);
                        checked = true;
                        break;
                    }
                }
                if checked {
                    break;
                }
            }
            if checked {
                break;
            }
        }
        assert!(checked);
    }

