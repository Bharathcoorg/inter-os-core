//! The InterOS 16x24 condensed bitmap sans — the shell's typeface.
//!
//! WHY this file exists: the shell had exactly one face, `FONT_8X8`, an 8x8
//! fixed cell defined in `main.rs`. A fixed cell is the single largest constraint
//! on visual quality in this project. Every stem is a block of `scale` pixels, so
//! the lock-screen clock at 12x is twelve-pixel-wide strokes and the body text at
//! 3x is three-pixel-wide strokes: pixel art, not a phone. Worse, the cell is
//! *square*, so the face cannot be condensed at all — only shrunk. The reference
//! design's typeface is 1.68x more condensed than this, which is why no integer
//! scale could match the reference clock on both axes at once.
//!
//! This face is drawn for that: a 16x24 cell with a 17-row cap height, a
//! 13-row x-height (round sides overshoot to row 7), 2 px stems, 1 px
//! overshoot on round-sided letters, and **real proportional advances** — `i`
//! costs 6 px, `m` and `W` cost 16, and the figures are tabular at 11 px so a
//! clock never shifts sideways as it ticks.
//!
//! # The letterforms come from a real typeface
//!
//! Every bitmap in this file is rasterised from **Roboto Condensed** — the
//! condensed cut of Android's system family, Apache License 2.0, committed
//! under `tools/fonts/` with its licence — by `tools/gen_font.py`. Roboto is
//! rendered at 4x and area-downsampled into the fixed 16x24 cell, so the
//! letterforms are recognisable smartphone typography rather than hand-placed
//! strokes, while every metric on this page stays exactly what the firmware
//! was designed around. Digits are resampled to 8 ink columns inside the
//! tabular advance; glyphs too wide for the cell (W, m) are clamped to 16 px;
//! descender tails that would pass row 23 are binned into rows 20..=23 so
//! they keep their shape instead of being sliced flat.
//!
//! Both the generator and its output are committed, so the firmware builds
//! without Python and the data is reproducible and auditable. The generator
//! self-checks every metric the Rust tests below assert, so a bad
//! regeneration fails at generation time, not in `cargo test`.
//!
//! To regenerate the tables:
//!
//! ```text
//! python tools/gen_font.py
//! ```
//!
//! Do not hand-edit the tables between the two marker comments: the next run
//! overwrites everything in between.
//!
//! # Design constants
//!
//! | property        | value | why                                              |
//! |-----------------|-------|--------------------------------------------------|
//! | cell            | 16x24 | widest ink (`W`) fills it; room for a descender   |
//! | cap height      | 17    | rows 3..=19; the dominant vertical rhythm         |
//! | x-height        | 13    | rows 7..=19 with overshoot; 0.76 of cap            |
//! | ascender        | 18    | row 2, one row above the cap                      |
//! | descender depth | 4     | rows 20..=23, below the baseline at row 20         |
//! | stem            | 2     | Roboto Condensed's stem at this em reads as 2 px   |
//! | overshoot       | 1     | round letters exceed the cap/x-height and baseline |
//! | digit advance   | 11    | tabular; 11/17 = 0.65, against the reference's 0.68      |
//!
//! # Weights
//!
//! Two: [`FONT`] regular and [`FONT_BOLD`] bold. Bold is generated, not drawn —
//! it is the regular face dilated one pixel horizontally, which thickens every
//! stem from 2 px to 3 px while leaving crossbars 2 px tall, exactly as a real
//! bold weight does. Each glyph's bold advance is one wider for the same reason.
//!
//! Anti-aliasing is deliberately absent. At 16x24 a correctly proportioned
//! bitmap face is crisp, which is what a small screen wants; the win here is
//! shape and proportion, not smoothing, and there is no alpha channel to spend.

