    #[test]
    fn the_rasteriser_agrees_with_measure() {
        // Walk a real run the way `run_pixel` does and confirm the last inked
        // pixel of the run lands inside the measured width. If the pen walk and
        // `measure` ever disagreed, this is what would catch it.
        for scale in [1usize, 2, 3] {
            let text = &b"Room 108 Wifi"[..];
            let w = text::measure(text, scale);
            let mut pen = 0usize;
            let mut last_ink = 0usize;
            for &c in text {
                let adv = advance_of(c, false) * scale;
                for x in 0..adv {
                    for y in 0..GLYPH_H * scale {
                        if run_pixel(pen + x, y, 0, 0, scale, text, false).is_some()
                            && run_pixel(pen + x, y, 0, 0, scale, text, false)
                                .map(|hit| hit.0)
                                == Some(c)
                        {
                            last_ink = pen + x + 1;
                        }
                    }
                }
                pen += adv;
            }
            assert!(pen == w, "pen walk {} != measure {}", pen, w);
            assert!(last_ink <= w, "ink at {} escaped the measured width {}", last_ink, w);
            assert!(last_ink > 0, "the sample run drew nothing");
        }
    }

    #[test]
    fn the_rasteriser_is_transparent_outside_the_run() {
        let text = &b"12:34"[..];
        let w = text::measure(text, 2);
        let h = text::line_height(2);
        // Right of the run, below it, and above it.
        for x in [w, w + 1, w + 40] {
            assert!(
                run_pixel(x, 4, 0, 0, 2, text, false).is_none(),
                "pixel at x={} should be past the run",
                x
            );
        }
        for y in [h, h + 1] {
            assert!(
                run_pixel(0, y, 0, 0, 2, text, false).is_none(),
                "pixel at y={} should be past the line",
                y
            );
        }
        // A negative offset is not a pixel; it must not underflow.
        assert!(run_pixel(0, 0, 4, 4, 2, text, false).is_none());
        // And the run does draw something inside its own box. WHY scan for it:
        // the first glyph is a '1', which is centred in a tabular advance and so
        // has no ink at column 0 -- asserting a specific pixel would be
        // asserting a detail of that glyph rather than of the rasteriser.
        let mut inked = false;
        for x in 0..w {
            for y in 0..h {
                if run_pixel(x, y, 0, 0, 2, text, false).is_some() {
                    inked = true;
                }
            }
        }
        assert!(inked, "the sample run drew nothing inside its own line box");
        // Every inked pixel belongs to the glyph the pen walk says it does.
        for x in 0..w {
            for y in 0..h {
                if let Some(hit) = run_pixel(x, y, 0, 0, 2, text, false) {
                    assert!(
                        pixel(hit.0, hit.1, hit.2, false),
                        "run_pixel reported ink the glyph does not have"
                    );
                }
            }
        }
    }
