pub const ADVANCE_BOLD: [u8; 95] = [6, 7, 9, 14, 13, 16, 14, 5, 9, 9, 11, 13, 6, 7, 7, 10, 12, 12, 12, 12, 12, 12, 12, 12, 12, 12, 7, 6, 12, 12, 12, 11, 17, 15, 14, 15, 15, 13, 13, 15, 16, 7, 13, 14, 12, 17, 16, 15, 14, 15, 14, 13, 13, 14, 14, 17, 14, 14, 14, 7, 10, 7, 10, 11, 8, 12, 13, 12, 13, 12, 9, 13, 13, 6, 6, 12, 6, 17, 13, 13, 13, 13, 8, 12, 8, 13, 11, 17, 12, 11, 12, 8, 7, 8, 15];
pub const FALLBACK_ADVANCE: usize = 6;

/// Horizontal advance of `c` in pixels, before scaling.
///
/// WHY a lookup and not a formula: proportional metrics are the entire reason
/// this face exists. A formula would make it another fixed cell.
#[inline]
pub fn advance_of(c: u8, bold: bool) -> usize {
    match glyph_index(c) {
        Some(i) => {
            if bold {
                ADVANCE_BOLD[i] as usize
            } else {
                ADVANCE[i] as usize
            }
        }
        None => FALLBACK_ADVANCE,
    }
}

/// One glyph's bitmap rows, or `None` for a byte with no glyph.
///
/// Each element is one row, most-significant bit = leftmost pixel, so a pixel
/// test is `(rows[row] >> (GLYPH_W - 1 - col)) & 1`.
#[inline]
pub fn glyph_rows(c: u8, bold: bool) -> Option<&'static [u16]> {
    let i = glyph_index(c)?;
    let table: &[u16] = if bold { &FONT_BOLD } else { &FONT };
    Some(&table[i * GLYPH_H..i * GLYPH_H + GLYPH_H])
}

/// Whether the pixel at glyph-space `(col, row)` of `c` is ink.
#[inline]
pub fn pixel(c: u8, col: usize, row: usize, bold: bool) -> bool {
    if col >= GLYPH_W || row >= GLYPH_H {
        return false;
    }
    match glyph_rows(c, bold) {
        Some(rows) => (rows[row] >> (GLYPH_W - 1 - col)) & 1 == 1,
        None => false,
    }
}

/// Ink bounds of a glyph as `(left, right, top, bottom)` in glyph space, or
/// `None` if it is blank (only the space glyph is).
///
/// Exposed for the specimen tooling and the proportion tests; the rasteriser
/// itself never needs it.
pub fn ink_bounds(c: u8, bold: bool) -> Option<(usize, usize, usize, usize)> {
    let rows = glyph_rows(c, bold)?;
    let mut left = GLYPH_W;
    let mut right = 0usize;
    let mut top = GLYPH_H;
    let mut bottom = 0usize;
    for (y, word) in rows.iter().enumerate() {
        if *word == 0 {
            continue;
        }
        for x in 0..GLYPH_W {
            if (word >> (GLYPH_W - 1 - x)) & 1 == 1 {
                if x < left {
                    left = x;
                }
                if x > right {
                    right = x;
                }
                if y < top {
                    top = y;
                }
                if y > bottom {
                    bottom = y;
                }
            }
        }
    }
    if right == 0 && left == GLYPH_W {
        None
    } else {
        Some((left, right, top, bottom))
    }
}

/// Rasterises one device pixel of a run of text, returning the glyph it landed
/// in as `(byte, column, row)` in glyph space, or `None` for transparent.
///
/// THIS IS THE FUNCTION `main.rs` NEEDS. The old inlined rasteriser in `main.rs`
/// computed the glyph from `(x - x0) / char_w`, which is only correct when every
/// character is the same width. With proportional advances the pen has to be
/// walked, which is what this does; it is the single change that switches the
/// shell over to this face.
///
/// Contract, matching the function it replaces:
///   * `x0, y0` is the top-left of the *first glyph cell*, and the run advances
///     left to right by each glyph's own advance.
///   * `scale` is an integer multiplier of both axes.
///   * a pixel outside `y0 .. y0 + GLYPH_H * scale`, or left of `x0`, is `None`.
///   * a pixel inside a glyph's advance but on a transparent pixel is `None`.
#[inline]
pub fn run_pixel(
    x: usize,
    y: usize,
    x0: usize,
    y0: usize,
    scale: usize,
    text: &[u8],
    bold: bool,
) -> Option<(u8, usize, usize)> {
    if scale == 0 || text.is_empty() {
        return None;
    }
    let row = (y.checked_sub(y0)?) / scale;
    if row >= GLYPH_H {
        return None;
    }
    let dx = x.checked_sub(x0)?;
    let mut pen = 0usize;
    for &c in text {
        let adv = advance_of(c, bold) * scale;
        if dx < pen + adv {
            let col = (dx - pen) / scale;
            return if pixel(c, col, row, bold) {
                Some((c, col, row))
            } else {
                None
            };
        }
        pen += adv;
    }
    None
}

